type Pol = Record<string, any>;
/** The release-policy values an approving officer may change here. Every other value (roles, admin checks, the hold rule)
 * is fixed by the solution document or needs a code change, and is shown read-only through the history. */
const EDITABLE: { path: string; label: string; kind: 'days' | 'minutes' | 'bool' }[] = [
  { path: 'release.fdr_current_instrument_max_evidence_age_days', label: 'Bank confirmation at release: maximum age (days)', kind: 'days' },
  { path: 'release.fdr_evidence_must_postdate_last_maturity', label: 'Confirmation must post-date the last maturity', kind: 'bool' },
  { path: 'release.allow_partial_release_of_undisputed_amount', label: 'Allow partial release of the undisputed amount', kind: 'bool' },
  { path: 'payments.confirmation_window_minutes.RTGS', label: 'RTGS: wait for credit confirmation (minutes)', kind: 'minutes' },
  { path: 'payments.confirmation_window_minutes.NEFT', label: 'NEFT: wait for credit confirmation (minutes)', kind: 'minutes' },
  { path: 'payments.reissue_target_working_days', label: 'Re-issue a returned payment within (working days)', kind: 'days' },
];
const getAt = (o: Pol, path: string) => path.split('.').reduce<any>((x, k) => x?.[k], o);
function setAt(o: Pol, path: string, v: unknown): Pol {
  const copy = structuredClone(o);
  const ks = path.split('.');
  ks.slice(0, -1).reduce<any>((x, k) => x[k], copy)[ks.at(-1)!] = v;
  return copy;
}

/** Release policy: approving AICTE roles only. Before and after are shown before publishing; the server records the same
 * difference, the reason and the officer in the hash-chained portal audit, and the ledger applies it to future commands. */
function ReleasePolicyEditor() {
  const { run } = useStore();
  const d = useApi<{ active: Pol; editable: boolean; versions: { id: number; created_at: string; created_by: string }[] }>('/policy');
  const [draft, setDraft] = useState<Pol | null>(null);
  const [reason, setReason] = useState('');
  useEffect(() => setDraft(d.data ? structuredClone(d.data.active) : null), [d.data]);
  if (d.error) return <Panel title="Release policy"><ErrorBox text={d.error} /></Panel>;
  if (!d.data || !draft) return <Panel title="Release policy"><Loading rows={4} /></Panel>;
  const changes = diffLeaves(d.data.active, draft);
  const v = d.data.versions[0];
  const publish = async () => {
    if (await run(() => api('/policy', { method: 'PUT', json: { policy: draft, reason } }), 'Release policy published') !== undefined) setReason('');
  };
  return (
    <Panel title="Release policy" sub={`${v ? `Version ${v.id} · ${v.created_by} · ${fmtDateTime(v.created_at)}` : 'Kernel defaults (TL-POLICY-v5), proposed for AICTE approval'}`}>
      {!d.data.editable && <p className="muted small">Read only: only a deputy director or director of AICTE can change the release policy.</p>}
      <div className="pol-form">
        {EDITABLE.map((f) => {
          const id = `pol-${f.path.replace(/\W/g, '-')}`;
          const val = getAt(draft, f.path);
          return f.kind === 'bool' ? (
            <label key={f.path} className="check" htmlFor={id} style={{ alignSelf: 'center' }}>
              <input id={id} type="checkbox" checked={!!val} disabled={!d.data!.editable} onChange={(e) => setDraft(setAt(draft, f.path, e.target.checked))} /> {f.label}
            </label>
          ) : (
            <label key={f.path} htmlFor={id}>{f.label}
              <input id={id} className="inp num" type="number" min={1} step={1} value={val ?? ''} disabled={!d.data!.editable}
                onChange={(e) => setDraft(setAt(draft, f.path, e.target.value === '' ? '' : Number(e.target.value)))} />
            </label>
          );
        })}
      </div>
      <h3 className="small" style={{ marginTop: 14, color: 'var(--navy)' }}>Before and after</h3>
      <DiffTable changes={changes} caption="Release policy: values before and after this change" />
      {d.data.editable && (
        <div className="pol-form">
          <label htmlFor="pol-reason">Reason for the change (required, recorded in the audit trail)
            <input id="pol-reason" className="inp" value={reason} onChange={(e) => setReason(e.target.value)} placeholder="e.g. Council resolution 2026/14, item 6" />
          </label>
          <div style={{ display: 'flex', gap: 8 }}>
            <button className="btn btn-primary" disabled={!changes.length || reason.trim().length < 10} onClick={publish}>Publish new version</button>
            <button className="btn btn-ghost" disabled={!changes.length} onClick={() => setDraft(structuredClone(d.data!.active))}>Discard</button>
          </div>
        </div>
      )}
    </Panel>
  );
}

